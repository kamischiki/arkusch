/* One random clip + links.
   - Clips: A.reelsManifest (generated by prerender.py from the videos/ folder), falling back to
     A.config.reels. Videos are self-hosted: nothing is loaded from third parties.
   - Order: shuffled; "Show another video" walks through the shuffle so nothing repeats until
     every clip has been shown.
   - Loading: preload="none"; the first clip gets its src when the player is near the viewport
     (first frame only until it plays). It plays muted while >= 60% visible; a visitor's Pause is
     respected until they press Play (WCAG 2.2.2).
   - Reduced motion / Data Saver: no autoplay, native controls, nothing downloads until play.
   - Links: A.config.social = { medium, youtube, instagram, website }. A link without a URL stays hidden. */
(function () {
  var A = window.Arkusch;
  var reduceMotion = window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches;
  var conn = navigator.connection || {};
  var manual = reduceMotion || !!conn.saveData || !("IntersectionObserver" in window);
  // Fallbacks when a URL is missing from config.social (config.js wins when it has a value).
  var DEFAULT_LINKS = {
    medium: "https://medium.com/code-like-a-girl/i-told-my-mom-not-to-touch-her-phone-3744cdd13d62",
    instagram: "https://www.instagram.com/hannakamyshanska/",
    website: "https://kamischiki.github.io/"
  };
  var noop = function () {};

  // The static /de/ and /uk/ copies live one folder deeper than videos/ and images/.
  function path(p) {
    if (/^([a-z]+:)?\/\//i.test(p) || p.charAt(0) === "/") return p;
    return (document.documentElement.hasAttribute("data-page-lang") ? "../" : "") + p;
  }

  function shuffle(a) {
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1)), t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  function setupLinks() {
    var cfg = A.config.social || {};
    document.querySelectorAll("[data-social]").forEach(function (li) {
      var key = li.dataset.social;
      var url = cfg[key] || DEFAULT_LINKS[key] || "";
      if (!url) return;
      var a = li.querySelector("a");
      a.href = url; a.target = "_blank"; a.rel = "noopener noreferrer";
      li.hidden = false;
    });
  }
  function labelLinks() {
    document.querySelectorAll("[data-social] a[target]").forEach(function (a) {
      a.setAttribute("aria-label", a.textContent + " (" + A.i18n.t("reels.newTab") + ")");
    });
  }

  function initPlayer(list) {
    var box = document.querySelector(".clip");
    var media = document.getElementById("clip-media");
    var video = document.getElementById("clip-video");
    var toggle = document.getElementById("clip-toggle");
    var sound = document.getElementById("clip-sound");
    var next = document.getElementById("clip-next");
    media.hidden = false;
    video.muted = true;             // make sure the muted state matches the attribute
    box.classList.add("clip--has-media");

    var order = shuffle(list.map(function (_, i) { return i; }));
    var pos = 0, current = order[0];
    var loaded = false, visible = false, userPaused = false;

    // Poster right away (a small image), so the card is never an empty box while the video waits.
    var first = list[current];
    if (first.poster) video.poster = path(first.poster);
    video.addEventListener("error", function () {
      console.warn("Arkusch clip failed to load:", video.currentSrc || video.getAttribute("src"),
        "- check that this file exists on the site and is H.264 MP4");
    });
    video.addEventListener("loadeddata", function () { video.classList.add("is-ready"); });

    function load(i, playNow) {
      var reel = list[i];
      video.pause();
      if (reel.poster) video.poster = path(reel.poster); else video.removeAttribute("poster");
      if (manual) { video.preload = "none"; video.src = path(reel.src); }
      else { video.preload = playNow ? "auto" : "metadata"; video.src = path(reel.src) + "#t=0.1"; }
      loaded = true; userPaused = false;
      if (playNow) video.play().catch(noop);
    }
    function sync() {   // play only while visible and not paused by the visitor
      if (manual || !loaded) return;
      if (visible && !userPaused) video.play().catch(noop); else if (!visible) video.pause();
    }
    function labels() {
      toggle.textContent = A.i18n.t(video.paused ? "reels.play" : "reels.pause");
      sound.textContent = A.i18n.t(video.muted ? "reels.soundOn" : "reels.soundOff");
      video.setAttribute("aria-label", A.i18n.t("reels.videoLabel"));
    }

    if (manual) {
      video.controls = true;          // native controls; custom play/sound buttons not needed
      toggle.hidden = true; sound.hidden = true;
      load(current, false);
    } else {
      var near = new IntersectionObserver(function (es) {
        if (es[0].isIntersecting) { near.disconnect(); if (!loaded) { load(current, false); sync(); } }
      }, { rootMargin: "200px 0px" });
      near.observe(video);
      new IntersectionObserver(function (es) { visible = es[0].intersectionRatio >= 0.6; sync(); },
        { threshold: [0, 0.3, 0.6, 0.9] }).observe(video);
    }

    function userToggle() {
      if (!loaded) { load(current, true); return; }
      if (video.paused) { userPaused = false; video.play().catch(noop); }
      else { userPaused = true; video.pause(); }
    }
    toggle.addEventListener("click", userToggle);
    if (!manual) video.addEventListener("click", userToggle);
    video.addEventListener("play", labels);
    video.addEventListener("pause", labels);

    sound.addEventListener("click", function () {
      if (!loaded) load(current, false);
      video.muted = !video.muted;
      if (!video.muted) { userPaused = false; video.play().catch(noop); }
      labels();
    });

    if (list.length < 2) next.hidden = true;
    next.addEventListener("click", function () {
      pos++;
      if (pos >= order.length) {      // all shown: reshuffle, never start with the clip just seen
        order = shuffle(order);
        if (order[0] === current && order.length > 1) { var t = order[0]; order[0] = order[1]; order[1] = t; }
        pos = 0;
      }
      current = order[pos];
      load(current, !manual);
      labels();
    });

    document.addEventListener("arkusch:lang", labels);
    labels();
  }

  A.reels = {
    init: function () {
      if (!document.getElementById("clip")) return;
      setupLinks(); labelLinks();
      document.addEventListener("arkusch:lang", labelLinks);

      var list = (A.reelsManifest && A.reelsManifest.length) ? A.reelsManifest : (A.config.reels || []);
      var media = document.getElementById("clip-media");
      if (list.length && media) initPlayer(list);
      else if (media) media.remove();   // no clips: the section keeps just the text and links
    }
  };
})();